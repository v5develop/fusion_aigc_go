#!/usr/bin/env python3
"""重新生成 pkg/jsoncase/known_gen.go：收集网关 / admin 的 snake_case json 标签作为请求侧白名单。

用法（仓库根目录）：python3 scripts/jsoncase/gen_known.py
新增含下划线的 json 字段后必须重跑。
"""
import glob
import re

SOURCES = [
    "app/gateway/api/internal/types/types.go",
    "app/admin/api/internal/types/types.go",
    *glob.glob("app/gateway/api/*.api"),
    *glob.glob("app/admin/api/*.api"),
]
PAT = re.compile(r'(?:json|form):"([a-z0-9]+(?:_[a-z0-9]+)+)(?:,[^"]*)?"')  # json 标签 + query 的 form 标签（query 名也允许请求体携带）

names = set()
for path in SOURCES:
    with open(path, encoding="utf-8") as f:
        names.update(PAT.findall(f.read()))

lines = [
    "// Code generated by scripts/jsoncase/gen_known.py; DO NOT EDIT.",
    "// 由两个服务的 json 标签收集的 snake_case 字段名，用于请求侧 camelCase → snake_case 的白名单。",
    "",
    "package jsoncase",
    "",
    "var knownSnake = map[string]bool{",
]
lines += [f'\t"{n}": true,' for n in sorted(names)]
lines.append("}")
with open("pkg/jsoncase/known_gen.go", "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"{len(names)} known snake names -> pkg/jsoncase/known_gen.go")
