#!/usr/bin/env python3
"""重新生成 pkg/jsoncase/known_gen.go，产出两张表：

1. knownSnake：网关 / admin 的 snake_case json / form(query) / path 标签，作为请求侧（请求体 + query）
   camelCase → snake_case 的白名单。
2. freeFormKeys：类型为自由格式的 json 字段名（interface{} / any / json.RawMessage / map[...]，
   含指针、切片包装），中间件改写请求体与给响应补别名时都不下钻这些键的值（原样保留字节）——
   画布快照、工具参数、Java 透传配置等是调用方私有 JSON，里面的键不是接口字段，不得改名或补别名。
   字符串承载的 JSON 文本（如 params / payload / script 为 string）本身就是 JSON 字符串，中间件
   不会解析其内容，无需列入。

自由格式名按「全局字段名」生效，所以同名字段在别处若是具名结构体，脚本会校验该结构体（递归）里
没有任何含下划线的 json 键（否则跳过会让那条路由丢掉 camel 兼容），不满足就报错退出；
code / msg / data 是响应信封的键，禁止成为自由格式名（否则整个响应都不补别名）。

用法（仓库根目录）：python3 scripts/jsoncase/gen_known.py
新增含下划线的 json / form / path 字段，或新增自由格式字段后必须重跑；输出排序后写入，重复运行结果一致。
"""
import glob
import re
import subprocess
import sys

TYPES_GO = [
    "app/gateway/api/internal/types/types.go",
    "app/admin/api/internal/types/types.go",
]
SOURCES = [
    *TYPES_GO,
    *sorted(glob.glob("app/gateway/api/*.api")),
    *sorted(glob.glob("app/admin/api/*.api")),
]
PAT = re.compile(r'(?:json|form|path):"([a-z0-9]+(?:_[a-z0-9]+)+)(?:,[^"]*)?"')  # json 标签 + query 的 form 标签 + 路径参数的 path 标签
RESERVED = {"code", "msg", "data"}  # 响应信封
# 类型虽是自由格式、但值里的键就是接口字段（文档按下划线命名、下游按下划线读）的字段：照常下钻补 snake。
# params：画布工具参数（api-canvas.md 3.2），canvas rpc 只读 aspect_ratio / image_url / mask_url 等下划线键，
# 而 web 试穿节点发的是 params.aspectRatio——不下钻会让用户选的比例被静默丢成默认 3:4。
DESCEND = {"params"}

names = set()
for path in SOURCES:
    with open(path, encoding="utf-8") as f:
        names.update(PAT.findall(f.read()))

# ---------------------------------------------------------------- 结构体解析（goctl 生成的 types.go，格式规整）

STRUCT_START = re.compile(r"^type (\w+) struct \{\s*$")
FIELD = re.compile(r"^\s+(\w+)\s+([^\s`]+)\s+`([^`]*)`")
EMBED = re.compile(r"^\s+\*?(\w+)\s*(?://.*)?$")
JSON_TAG = re.compile(r'json:"([^",]*)')


def is_free_form(typ: str) -> bool:
    base = typ.lstrip("*[]")
    return base in ("interface{}", "any", "json.RawMessage") or base.startswith("map[")


structs = {}  # (文件, 结构体名) 无需区分：两服务各自的 types 包里同名结构体合并字段，只用于安全校验
for path in TYPES_GO:
    cur = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if cur is None:
                m = STRUCT_START.match(line)
                if m:
                    cur = structs.setdefault(m.group(1), [])
                continue
            if line.startswith("}"):
                cur = None
                continue
            m = FIELD.match(line)
            if m:
                jm = JSON_TAG.search(m.group(3))
                if jm and jm.group(1) and jm.group(1) != "-":
                    cur.append((jm.group(1), m.group(2)))
                continue
            m = EMBED.match(line)
            if m:
                cur.append(("", m.group(1)))  # 内嵌结构体：键平铺在本层


def struct_of(typ: str):
    base = typ.lstrip("*[]")
    if base.startswith("map["):
        base = base[base.index("]") + 1:].lstrip("*[]")
    return base if base in structs else None


def underscore_keys(sname: str, seen=None) -> set:
    """结构体（递归）里所有含下划线的 json 键。"""
    seen = seen if seen is not None else set()
    if sname in seen:
        return set()
    seen.add(sname)
    out = set()
    for key, typ in structs[sname]:
        if "_" in key:
            out.add(key)
        sub = struct_of(typ)
        if sub:
            out |= underscore_keys(sub, seen)
    return out


free = {}  # json 名 -> 出处
for sname, fields in structs.items():
    for key, typ in fields:
        if key and key not in DESCEND and is_free_form(typ):
            free.setdefault(key, []).append(f"{sname}.{key} {typ}")

errors = []
for key in sorted(free):
    if key in RESERVED:
        errors.append(f"自由格式字段名 {key!r} 与响应信封键冲突：{free[key]}")
    for sname, fields in structs.items():
        for k, typ in fields:
            sub = struct_of(typ)
            if k == key and sub and not is_free_form(typ):
                bad = underscore_keys(sub)
                if bad:
                    errors.append(
                        f"{key!r} 在 {free[key]} 是自由格式，但 {sname}.{key} 是含下划线键的结构体 {sub}{sorted(bad)}；"
                        "改字段名，或把本脚本改成按路由生成")
if errors:
    sys.exit("gen_known.py: " + "\n".join(errors))

lines = [
    "// Code generated by scripts/jsoncase/gen_known.py; DO NOT EDIT.",
    "// 由两个服务的 json / form / path 标签收集的 snake_case 字段名，用于请求侧（请求体与 URL query）camelCase → snake_case 的白名单。",
    "",
    "package jsoncase",
    "",
    "var knownSnake = map[string]bool{",
]
lines += [f'\t"{n}": true,' for n in sorted(names)]
lines += [
    "}",
    "",
    "// freeFormKeys 类型为自由格式（interface{} / any / json.RawMessage / map）的 json 字段名：",
    "// 请求改写与响应补别名都不下钻其值（值原样保留），键本身照常按所在层处理。",
    "var freeFormKeys = map[string]bool{",
]
for key in sorted(free):
    lines.append(f'\t"{key}": true, // ' + "; ".join(sorted(set(free[key]))))
lines.append("}")
with open("pkg/jsoncase/known_gen.go", "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
subprocess.run(["gofmt", "-w", "pkg/jsoncase/known_gen.go"], check=True)  # 与手写代码同样对齐
print(f"{len(names)} known snake names, {len(free)} free-form keys -> pkg/jsoncase/known_gen.go")
