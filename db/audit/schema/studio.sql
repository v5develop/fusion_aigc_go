CREATE TABLE `afv_studio_batch` (
  `id`               bigint        NOT NULL AUTO_INCREMENT COMMENT '主键ID（批次号）',
  `user_id`          bigint        NOT NULL COMMENT '提交用户ID',
  `workspace_id`     bigint        NOT NULL DEFAULT '0' COMMENT '所属工作空间ID；0=个人空间',
  `kind`             enum('tryon','pose','imagegen') NOT NULL COMMENT '类型：tryon-商拍换装 pose-姿态复刻 imagegen-图片生成',
  `request_id`       varchar(64)   NOT NULL COMMENT '客户端幂等键（Idempotency-Key），同用户唯一',
  `payload`          json          NOT NULL COMMENT '前端提交的全量字段快照（历史回填、重做都以它为准）',
  `payload_hash`     char(64)      NOT NULL DEFAULT '' COMMENT 'payload 规范化后的 SHA-256 十六进制；同用户同指纹短窗口归并用',
  `source_sha1`      char(40)      DEFAULT NULL COMMENT '姿态复刻人物图（source）的 SHA-1；同图复用 source 反推缓存。其它类型为空',
  `estimated_points` bigint        NOT NULL DEFAULT '0' COMMENT '提交时预估消耗点数（单价×任务数，以预留单为准）',
  `status`           tinyint       NOT NULL DEFAULT '0' COMMENT '批次状态：0-排队 1-切图中 2-反推中 3-生图中 4-全部成功 5-全部失败 6-部分成功 7-已取消',
  `crop_plan`        json          DEFAULT NULL COMMENT '切图方案（sidecar crop-plan 的 plans，框为 0-1 归一化）；仅商拍',
  `crop_check`       json          DEFAULT NULL COMMENT '切图质检结果（sidecar crop-check 的 results）；仅商拍',
  `selected_images`  json          DEFAULT NULL COMMENT '组图结果：每个模特最终送生图的图序 [{model_index, images:[{id,url,role,sha1}]}]',
  `step_log`         json          DEFAULT NULL COMMENT '每步耗时与成本 [{step,ms,images,crops,degraded,cost_cny,at}]；不记 base64/Key/完整 prompt',
  `task_total`       int           NOT NULL DEFAULT '0' COMMENT '子任务总数（模特×张数 / 姿势数 / count）',
  `task_done`        int           NOT NULL DEFAULT '0' COMMENT '已成功的子任务数',
  `task_failed`      int           NOT NULL DEFAULT '0' COMMENT '已失败（含取消）的子任务数',
  `error_reason`     varchar(255)  DEFAULT NULL COMMENT '批次级失败原因（切图 / 反推整批失败等）',
  `deleted`          tinyint       NOT NULL DEFAULT '0' COMMENT '逻辑删除标志：1-用户已删除',
  `lease_owner`      varchar(64)   DEFAULT NULL COMMENT '租约持有者（studio-rpc 实例 hostname-pid-随机）：编排阶段同一批次只由一个实例推进；多实例部署用',
  `lease_until`      datetime(3)   DEFAULT NULL COMMENT '租约到期时间（库时钟 NOW(3)+TTL，编排 10 分钟、派发 3 分钟，心跳续租）；NULL 或已过期 = 可被任一实例抢占',
  `created_at`       datetime(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  `updated_at`       datetime(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  PRIMARY KEY (`id`) USING BTREE,
  UNIQUE KEY `uk_user_request` (`user_id`,`request_id`) USING BTREE,
  KEY `idx_user_created` (`user_id`,`created_at`) USING BTREE,
  KEY `idx_status` (`status`,`updated_at`) USING BTREE,
  KEY `idx_status_lease` (`status`,`lease_until`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci ROW_FORMAT=DYNAMIC COMMENT='studio 批次（一次提交）';

CREATE TABLE `afv_studio_task` (
  `id`                 bigint        NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `batch_id`           bigint        NOT NULL COMMENT '所属批次（afv_studio_batch.id）',
  `user_id`            bigint        NOT NULL COMMENT '提交用户ID（冗余，任务中心与计费按它关联）',
  `kind`               enum('tryon','pose','imagegen') NOT NULL COMMENT '类型，同批次；任务中心按它分入口',
  `model_index`        int           NOT NULL DEFAULT '0' COMMENT '模特序号（商拍，从 0 起）；其它类型为 0',
  `shot_index`         int           NOT NULL DEFAULT '0' COMMENT '同一模特的第几张（商拍）/ 第几张（图片生成），从 0 起',
  `pose_index`         int           NOT NULL DEFAULT '0' COMMENT '姿势序号（姿态复刻，从 0 起）；其它类型为 0',
  `task_id`            varchar(64)   DEFAULT NULL COMMENT '对外任务号：aigc.NewLifeTaskID(前缀, taskcenter.Ref(前缀,id), 步骤)，前缀 tyo/pse/simg（不含下划线）；插入后回填',
  `attempt`            int           NOT NULL DEFAULT '0' COMMENT '第几次生成（运营重做 +1）；与 batch_id/model/shot 组成 gateway 幂等键',
  `model_group`        varchar(64)   NOT NULL DEFAULT '' COMMENT 'ai-gateway model group 码，如 img.gpt-image-2',
  `input_images`       json          DEFAULT NULL COMMENT '实际送生图的图序：图1=模特/人物，图2..N=服装细节/姿势图 [{url,role}]',
  `prompt_text`        mediumtext    COMMENT '生图提示词（首行图序声明 + 反推正文，正文逐字不改）',
  `prompt_meta`        json          DEFAULT NULL COMMENT '反推元信息（degraded/vision/warning、姿态 pose 字段等）',
  `gateway_call_id`    varchar(64)   DEFAULT NULL COMMENT 'ai-gateway /v1/calls 返回的调用号',
  `gateway_status`     varchar(32)   DEFAULT NULL COMMENT 'ai-gateway 调用状态原文（queued/running/succeeded/failed/canceled 等）',
  `status`             tinyint       NOT NULL DEFAULT '0' COMMENT '任务状态：0-排队 1-生成中 2-成功 3-失败 4-已取消',
  `admin_locked`       tinyint       NOT NULL DEFAULT '0' COMMENT '运营强制失败：1=封禁运营重做',
  `result_rid`         varchar(128)  DEFAULT NULL COMMENT '产物资源号（ai-gateway mr:// 或 media 服务 rid）',
  `result_url`         varchar(1024) DEFAULT NULL COMMENT '转存到公有桶后的成品地址',
  `result_width`       int           NOT NULL DEFAULT '0' COMMENT '成品宽（像素）',
  `result_height`      int           NOT NULL DEFAULT '0' COMMENT '成品高（像素）',
  `cost_cny`           decimal(12,6) NOT NULL DEFAULT '0.000000' COMMENT '上游成本（人民币，gateway cost.amount_cny）',
  `billing_request_id` varchar(128)  DEFAULT NULL COMMENT '计费请求号（billing.Charge.RequestID，如 studio-<task_id>；超 64 字节时 biz_id 取 SHA-256），任务中心按它关联预留单',
  `billing_status`     tinyint       NOT NULL DEFAULT '0' COMMENT '计费状态：0-未计费 1-已冻结 2-已结算 3-已退回 4-影子模式（不动账）',
  `error_reason`       varchar(255)  DEFAULT NULL COMMENT '失败原因（展示给用户的口径）',
  `started_at`         datetime(3)   DEFAULT NULL COMMENT '开始生图时间（提交 gateway）',
  `finished_at`        datetime(3)   DEFAULT NULL COMMENT '进入终态时间',
  `deleted`            tinyint       NOT NULL DEFAULT '0' COMMENT '逻辑删除标志（随批次删除置 1，任务中心同步删除态）',
  `lease_owner`        varchar(64)   DEFAULT NULL COMMENT '租约持有者（studio-rpc 实例 hostname-pid-随机）：生成 / 交付阶段同一子任务只由一个实例提交与轮询',
  `lease_until`        datetime(3)   DEFAULT NULL COMMENT '租约到期时间（库时钟 NOW(3)+3 分钟，心跳续租）；NULL 或已过期 = 可被任一实例抢占（崩溃后自然接管）',
  `created_at`         datetime(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  `updated_at`         datetime(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间',
  PRIMARY KEY (`id`) USING BTREE,
  UNIQUE KEY `uk_task_id` (`task_id`) USING BTREE,
  KEY `idx_batch` (`batch_id`) USING BTREE,
  KEY `idx_status` (`status`,`updated_at`) USING BTREE,
  KEY `idx_status_lease` (`status`,`lease_until`) USING BTREE,
  KEY `idx_user_created` (`user_id`,`created_at`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci ROW_FORMAT=DYNAMIC COMMENT='studio 子任务（一张图）';

CREATE TABLE `afv_studio_prompt_cache` (
  `id`         bigint      NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `batch_id`   bigint      NOT NULL COMMENT '所属批次（afv_studio_batch.id）；缓存只在批次内复用',
  `cache_key`  varchar(80) NOT NULL COMMENT '缓存键：模特图 sha1 / 姿势图 sha1 / 人物图 sha1 / 切图批次号',
  `kind`       enum('analyze','source','prompt','crop_plan') NOT NULL COMMENT '缓存类型：analyze-商拍反推 source-姿态人物解析 prompt-姿态提示词 crop_plan-切图方案',
  `payload`    json        NOT NULL COMMENT 'sidecar 原始返回（不含 base64 图片）',
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  PRIMARY KEY (`id`) USING BTREE,
  UNIQUE KEY `uk_batch_key` (`batch_id`,`cache_key`,`kind`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci ROW_FORMAT=DYNAMIC COMMENT='studio 批次内反推/切图缓存';

